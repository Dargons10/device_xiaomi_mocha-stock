/*
 * These are the coefficients used in the Taylor series expansion to refine the log2(x) approximation.
 * They correspond to constants derived from expanding log2(x) around a known reference point, using ln(2) as the base.
 */
static const double S1 = 1.0 / LN2;
static const double S2 = -1.0 / (2.0 * LN2);
static const double S3 = 1.0 / (3.0 * LN2);
static const double S4 = -1.0 / (4.0 * LN2);
static const double S5 = 1.0 / (5.0 * LN2);
static const double S6 = -1.0 / (6.0 * LN2);

/**
 * __kernel_log2
 *
 * Approximates the logarithm base 2 (log2) for inputs within the range [1.0, 2.0).
 *
 * The function begins with a lookup in the precomputed table of log2 and reciprocal values,
 * then applies a Taylor series expansion to enhance the result's accuracy.
 *
 * @param x  The value for which log2(x) is to be calculated. Must be in the range [1.0, 2.0).
 * @return   The approximate value of log2(x).
 */
double __kernel_log2(double x) {
    double a, dx, dx2, log2a, taylor;
    uint32_t ixh, ixl, lut_index;
    uint64_t ix;

    /*
     * Step 1: Convert the floating-point number into its raw bit representation.
     * This lets us extract and manipulate the higher and lower bits for indexing into the lookup table.
     */
    ix = *(uint64_t*)&x;
    ixh = (ix >> 32) & 0xFFFFFFFF;
    ixl = ix & 0xFFFFFFFF;

    /*
     * Step 2: Adjust the high part of the bit pattern (`ixh`) to compute the index for the lookup table.
     * By tweaking the bits, we align `ixh` to point to the correct region of the table.
     */
    ixh += (1 << (20 - LUT_SIZE_SHIFT - 1));
    ixl = 0;
    ixh = (ixh & ~(0xFFFFF << (20 - LUT_SIZE_SHIFT)));

    /*
     * Step 3: Use the modified `ixh` to calculate the index into the lookup table.
     * The index is derived using bit shifts and constants to ensure accurate positioning.
     */
    lut_index = (ixh - 0x3FC00000 - 0x00300000) >> (20 - LUT_SIZE_SHIFT);

    /*
     * Step 4: Fetch the precomputed values from the lookup table.
     * `log2a` is the log2 approximation for that index, and `a` is the reciprocal value used in the Taylor expansion.
     */
    a = log2_lut[lut_index][1];
    log2a = log2_lut[lut_index][0];

    /*
     * Step 5: Compute the difference `dx = (x - a) / a`.
     * This difference acts as the starting point for the Taylor series expansion.
     */
    dx = (x - a) * a;
    dx2 = dx * dx;

    /*
     * Step 6: Apply the Taylor series expansion to refine the log2(x) approximation.
     * This step uses the precomputed constants S1 through S6 to calculate the final result.
     */
    taylor = S1 + S2 * dx;
    taylor = taylor + (S3 + S4 * dx) * dx2;
    taylor = taylor + (S5 + S6 * dx) * dx2 * dx2;

    /*
     * Step 7: Return the final result, which is the sum of log2(a) and the Taylor expansion.
     */
    return log2a + taylor * dx;
}
